// Lenguaje "phpx" (resaltado Monarch) y tema Islands Dark de JetBrains para Monaco.

export function registerPhp(monaco) {
  monaco.languages.register({ id: 'phpx' });
  monaco.languages.setLanguageConfiguration('phpx', {
    comments: { lineComment: '//', blockComment: ['/*', '*/'] },
    brackets: [['{', '}'], ['[', ']'], ['(', ')']],
    colorizedBracketPairs: [], // JetBrains no colorea los paréntesis
    autoClosingPairs: [
      { open: '{', close: '}' }, { open: '[', close: ']' }, { open: '(', close: ')' },
      { open: '"', close: '"', notIn: ['string'] }, { open: "'", close: "'", notIn: ['string', 'comment'] },
    ],
    surroundingPairs: [['{', '}'], ['[', ']'], ['(', ')'], ['"', '"'], ["'", "'"]],
    wordPattern: /(-?\d*\.\d\w*)|(\$?[^\s`~!@#%^&*()\-=+[{\]}\\|;:'",.<>/?]+)/g,
  });
  monaco.languages.setMonarchTokensProvider('phpx', {
    keywords: [
      'abstract', 'and', 'array', 'as', 'bool', 'break', 'callable', 'case', 'catch', 'class', 'clone', 'const',
      'continue', 'declare', 'default', 'die', 'do', 'echo', 'else', 'elseif', 'empty', 'enum', 'exit', 'extends',
      'false', 'final', 'finally', 'float', 'fn', 'for', 'foreach', 'from', 'function', 'global', 'goto', 'if',
      'implements', 'include', 'include_once', 'instanceof', 'insteadof', 'int', 'interface', 'isset', 'iterable',
      'list', 'match', 'mixed', 'namespace', 'never', 'new', 'null', 'object', 'or', 'parent', 'print', 'private',
      'protected', 'public', 'readonly', 'require', 'require_once', 'return', 'self', 'static', 'string', 'switch',
      'throw', 'trait', 'true', 'try', 'unset', 'use', 'var', 'void', 'while', 'xor', 'yield',
    ],
    tokenizer: {
      root: [
        [/<\?(php|=)?|\?>/, 'metatag'],
        [/#\[/, 'annotation', '@attribute'],
        [/\/\*\*(?!\/)/, 'comment.doc', '@docblock'],
        [/\/\*/, 'comment', '@comment'],
        [/(\/\/|#).*$/, 'comment'],
        [/<<<\s*['"]?([a-zA-Z_]\w*)['"]?/, { token: 'string', next: '@heredoc.$1' }],
        [/"/, 'string', '@dstring'],
        [/'/, 'string', '@sstring'],
        [/\$this\b/, 'keyword'],
        [/\$[a-zA-Z_]\w*/, 'variable'],
        [/(\??->)(\s*)([a-zA-Z_]\w*)(?=\s*\()/, ['operator', '', 'method.call']],
        [/(\??->)(\s*)([a-zA-Z_]\w*)/, ['operator', '', 'field']],
        [/(::)(class)\b/, ['operator', 'keyword']],
        [/(::)(\$[a-zA-Z_]\w*)/, ['operator', 'field']],
        [/(::)([a-zA-Z_]\w*)(?!\s*\()/, ['operator', 'constant']],
        [/(function|fn)(\s+)([a-zA-Z_]\w*)/, ['keyword', '', 'function.decl']],
        [/(class|interface|trait|enum|extends|implements|new|instanceof|use)(\s+)(?!(?:self|static|parent|class|function)\b)([a-zA-Z_\\][\w\\]*)/, ['keyword', '', 'type']],
        [/[a-zA-Z_\\][\w\\]*(?=\s*\()/, { cases: { '@keywords': 'keyword', '@default': 'function.call' } }],
        [/[a-zA-Z_\\][\w\\]*/, { cases: { '@keywords': 'keyword', '~[A-Z][A-Z0-9_]+': 'constant', '@default': 'identifier' } }],
        [/\d[\d_]*\.\d[\d_]*([eE][-+]?\d+)?/, 'number'],
        [/0[xX][0-9a-fA-F_]+|0[bB][01_]+|\d[\d_]*/, 'number'],
        [/[{}()[\]]/, '@brackets'],
        [/[;,]/, 'delimiter'],
        [/[=<>!+\-*/%&|^~?:.@]+/, 'operator'],
      ],
      dstring: [
        [/[^\\"${]+/, 'string'],
        [/\\./, 'string.escape'],
        [/\{(?=\$)/, 'string.escape', '@interp'],
        [/\$this\b/, 'keyword'],
        [/\$[a-zA-Z_]\w*/, 'variable'],
        [/[${]/, 'string'],
        [/"/, 'string', '@pop'],
      ],
      interp: [
        [/\}/, 'string.escape', '@pop'],
        [/\$this\b/, 'keyword'],
        [/\$[a-zA-Z_]\w*/, 'variable'],
        [/(\??->)([a-zA-Z_]\w*)(?=\()/, ['operator', 'method.call']],
        [/(\??->)([a-zA-Z_]\w*)/, ['operator', 'field']],
        [/'[^']*'/, 'string'],
        [/[^}]/, 'identifier'],
      ],
      sstring: [
        [/[^\\']+/, 'string'],
        [/\\./, 'string.escape'],
        [/'/, 'string', '@pop'],
      ],
      heredoc: [
        [/^\s*([a-zA-Z_]\w*)/, { cases: { '$1==$S2': { token: 'string', next: '@pop' }, '@default': 'string' } }],
        [/.+/, 'string'],
      ],
      comment: [
        [/[^*]+/, 'comment'],
        [/\*\//, 'comment', '@pop'],
        [/\*/, 'comment'],
      ],
      docblock: [
        [/@[a-zA-Z-]+/, 'comment.doc.tag'],
        [/[^*@]+/, 'comment.doc'],
        [/\*\//, 'comment.doc', '@pop'],
        [/[*@]/, 'comment.doc'],
      ],
      attribute: [
        [/\]/, 'annotation', '@pop'],
        [/[^\]]+/, 'annotation'],
      ],
    },
  });

  monaco.editor.defineTheme('islands-dark', {
    base: 'vs-dark',
    inherit: true,
    rules: [
      { token: '', foreground: 'BCBEC4' },
      { token: 'keyword', foreground: 'CF8E6D' },
      { token: 'metatag', foreground: 'CF8E6D' },
      { token: 'string', foreground: '6AAB73' },
      { token: 'string.escape', foreground: 'CF8E6D' },
      { token: 'number', foreground: '2AACB8' },
      { token: 'comment', foreground: '7A7E85' },
      { token: 'comment.doc', foreground: '5F826B', fontStyle: 'italic' },
      { token: 'comment.doc.tag', foreground: '67A37C', fontStyle: 'italic bold' },
      { token: 'function.decl', foreground: '56A8F5' },
      { token: 'function.call', foreground: '57AAF7' },
      { token: 'method.call', foreground: '57AAF7' },
      { token: 'field', foreground: 'C77DBB' },
      { token: 'constant', foreground: 'C77DBB', fontStyle: 'italic' },
      { token: 'variable', foreground: 'BCBEC4' },
      { token: 'type', foreground: 'BCBEC4' },
      { token: 'identifier', foreground: 'BCBEC4' },
      { token: 'annotation', foreground: 'B3AE60' },
      { token: 'operator', foreground: 'BCBEC4' },
      { token: 'delimiter', foreground: 'BCBEC4' },
    ],
    colors: {
      'editor.background': '#1E1F22',
      'editor.foreground': '#BCBEC4',
      'editorLineNumber.foreground': '#4B5059',
      'editorLineNumber.activeForeground': '#A1A3AB',
      'editor.lineHighlightBackground': '#26282E',
      'editor.lineHighlightBorder': '#00000000',
      'editor.selectionBackground': '#214283',
      'editor.inactiveSelectionBackground': '#21428380',
      'editor.selectionHighlightBackground': '#37373D',
      'editor.wordHighlightBackground': '#37373D',
      'editorCursor.foreground': '#CED0D6',
      'editorIndentGuide.background1': '#2E3034',
      'editorIndentGuide.activeBackground1': '#4B5059',
      'editorBracketMatch.background': '#43454A',
      'editorBracketMatch.border': '#00000000',
      'editorError.foreground': '#F75464',
      'editorWarning.foreground': '#E0BB65',
      'editorInfo.foreground': '#868A91',
      'editorWidget.background': '#2B2D30',
      'editorWidget.border': '#393B40',
      'editorSuggestWidget.background': '#2B2D30',
      'editorSuggestWidget.border': '#393B40',
      'editorSuggestWidget.selectedBackground': '#2E436E',
      'editorHoverWidget.background': '#2B2D30',
      'editorHoverWidget.border': '#393B40',
      'scrollbarSlider.background': '#4B505955',
      'scrollbarSlider.hoverBackground': '#4B5059AA',
      'scrollbarSlider.activeBackground': '#5A5D63AA',
      'editorOverviewRuler.border': '#00000000',
    },
  });
}
